  expect(screen.getByRole('button', { name: 'Tải Word' })).toBeTruthy()
  expect(screen.getByRole('button', { name: 'Tải Excel' })).toBeTruthy()
  expect(screen.getByRole('button', { name: 'Tải PDF' })).toBeTruthy()
