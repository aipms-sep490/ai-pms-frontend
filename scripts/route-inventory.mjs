import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const rootDir = path.resolve(__dirname, '..')

const routerFile = path.resolve(rootDir, 'src/app/router/index.tsx')
const content = fs.readFileSync(routerFile, 'utf8')

// Parse routes from src/app/router/index.tsx
const routeRegex = /\{\s*path:\s*['"`]([^'"`]+)['"`],\s*element:\s*<([A-Za-z0-9]+)/g
const matches = []
let match

// We also manually inspect the tree structure or regex to capture role / guard / feature flag
const lines = content.split('\n')
let currentRole = 'Public / Authenticated'
let currentGuard = 'None'
let currentFeatureFlag = 'None'

const routes = []

// Walk line by line to maintain scope
for (let i = 0; i < lines.length; i++) {
  const line = lines[i]

  // RoleRoute tracking
  const roleMatch = line.match(/<RoleRoute allowed=\{\[([^\]]+)\]\}/)
  if (roleMatch) {
    currentRole = roleMatch[1].replace(/['"\s]/g, '')
  }

  // Guard tracking
  if (line.includes('<ActiveStudentProjectRoute')) {
    currentGuard = 'ActiveStudentProjectRoute'
  } else if (line.includes('<SupervisorExecutionRoute')) {
    currentGuard = 'SupervisorExecutionRoute'
  } else if (line.includes('<MentorExecutionRoute')) {
    currentGuard = 'MentorExecutionRoute'
  } else if (line.includes('<EvaluatorAssignmentRoute')) {
    currentGuard = 'EvaluatorAssignmentRoute'
  } else if (line.includes('<DepartmentAcademicScopeRoute')) {
    currentGuard = 'DepartmentAcademicScopeRoute'
  } else if (line.includes('<AdminEvaluationLayout')) {
    currentGuard = 'AdminEvaluationLayout'
  }

  // Feature flag tracking
  const envMatch = line.match(/env\.([a-zA-Z0-9]+)\s*\?/)
  if (envMatch) {
    currentFeatureFlag = `env.${envMatch[1]}`
  } else if (line.trim().startsWith('] : [])') || line.trim().endsWith('] : []),')) {
    currentFeatureFlag = 'None'
  }

  // Path match
  const pathMatch = line.match(/path:\s*['"`]([^'"`]+)['"`],\s*element:\s*<([A-Za-z0-9]+)/)
  if (pathMatch) {
    const rawPath = pathMatch[1]
    const component = pathMatch[2]
    routes.push({
      id: rawPath.replace(/[^a-zA-Z0-9]/g, '-').replace(/^-|-$/g, '') || 'root',
      path: rawPath.startsWith('/') ? rawPath : `/${rawPath}`,
      component,
      role: currentRole,
      guard: currentGuard,
      featureFlag: currentFeatureFlag,
    })
  }

  // Reset guard when layout/block ends
  if (line.includes('] },') && currentGuard !== 'None') {
    currentGuard = 'None'
  }
}

// Ensure uniqueness by path + role
const uniqueRoutes = []
const seen = new Set()
for (const r of routes) {
  const key = `${r.path}|${r.role}`
  if (!seen.has(key)) {
    seen.add(key)
    uniqueRoutes.push(r)
  }
}

console.log(`Found ${uniqueRoutes.length} executable routes in router index.tsx`)

// Generate Markdown
const mdHeader = `# ROUTE INVENTORY — AI-PMS Frontend
> Auto-generated by \`scripts/route-inventory.mjs\` from source HEAD (\`src/app/router/index.tsx\`).
> Total Routes Cataloged: **${uniqueRoutes.length}**

| ID | URL Path | Component | Allowed Roles | Route Guard | Feature Flag |
|---|---|---|---|---|---|
`

const mdRows = uniqueRoutes.map((r, idx) => {
  return `| ${idx + 1} | \`${r.path}\` | \`${r.component}\` | \`${r.role}\` | \`${r.guard}\` | \`${r.featureFlag}\` |`
}).join('\n')

const mdContent = `${mdHeader}${mdRows}\n`
const outMdPath = path.resolve(rootDir, 'docs/uiux/ROUTE_INVENTORY.generated.md')
fs.writeFileSync(outMdPath, mdContent, 'utf8')
console.log(`Written ${outMdPath}`)

// Generate CSV
const csvHeader = 'Index,RouteId,Path,Component,AllowedRoles,Guard,FeatureFlag\n'
const csvRows = uniqueRoutes.map((r, idx) => {
  return `${idx + 1},"${r.id}","${r.path}","${r.component}","${r.role}","${r.guard}","${r.featureFlag}"`
}).join('\n')

const outCsvPath = path.resolve(rootDir, 'docs/uiux/ROUTE_CENSUS.csv')
fs.writeFileSync(outCsvPath, `${csvHeader}${csvRows}\n`, 'utf8')
console.log(`Written ${outCsvPath}`)
