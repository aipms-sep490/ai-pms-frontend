import { readAssistantStreamResult } from './assistant-stream-result.mjs'
import { chromium } from '@playwright/test'
import { mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
const { ACADEMIC_TEST_EMAIL: email, ACADEMIC_TEST_PASSWORD: password, ACADEMIC_EVIDENCE_DIR: output } = process.env
if (!email || !password || !output) throw new Error('Provide test credentials and evidence directory through environment.')
mkdirSync(output, { recursive: true })
const browser = await chromium.launch({ headless: true, channel: 'msedge' })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('http://localhost:5175/profile')
  if (await page.getByRole('button', { name: 'Mở trợ lý AI' }).count()) throw new Error('Launcher visible before login')
  await page.getByLabel('Email', { exact: true }).fill(email)
  await page.getByLabel('Mật khẩu', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click()
  await page.waitForURL('**/profile')
  const initialUrl = page.url()
  const launcher = page.getByRole('button', { name: 'Mở trợ lý AI', exact: true })
  const aiBox = await launcher.boundingBox()
  const messageBox = await page.locator('.chat-launcher').boundingBox()
  if (messageBox && aiBox.y + aiBox.height > messageBox.y) throw new Error('Launchers overlap')
  await launcher.click()
  const dialog = page.getByRole('dialog', { name: 'Trợ lý AI', exact: true })
  await dialog.getByLabel('Câu hỏi học vụ').fill('Xin chào, bạn giúp được gì?')
  const responsePromise = page.waitForResponse(r => r.url().endsWith('/academic/assistant/stream'), { timeout: 65000 })
  await dialog.getByRole('button', { name: 'Gửi', exact: true }).click()
  const response = await responsePromise
  const answer = await readAssistantStreamResult(response, page)
  if (!response.ok() || !answer.runId) throw new Error('Real assistant request failed')
  await dialog.getByText(answer.answer, { exact: true }).waitFor()
  if (page.url() !== initialUrl) throw new Error('Assistant changed route')
  await dialog.getByLabel('Câu hỏi học vụ').fill('Bản nháp được giữ lại')
  await page.screenshot({ path: join(output, 'dock-desktop.png'), fullPage: true })
  await dialog.getByRole('button', { name: 'Thu nhỏ trợ lý AI', exact: true }).click()
  await launcher.click()
  if (await dialog.getByLabel('Câu hỏi học vụ').inputValue() !== 'Bản nháp được giữ lại') throw new Error('Draft lost')
  await page.locator('.chat-launcher').click()
  await dialog.waitFor({ state: 'hidden' })
  await launcher.click()
  if (await page.locator('#chat-dock-panel').isVisible()) throw new Error('Panels overlap')
  await dialog.getByRole('button', { name: 'Đóng trợ lý AI' }).click()
  await page.getByRole('link', { name: /Bảo mật tài khoản/ }).click()
  await launcher.click()
  await dialog.getByText(answer.answer, { exact: true }).waitFor()
  const downloading = page.waitForEvent('download')
  await dialog.getByRole('button', { name: 'Tải TXT' }).click()
  await (await downloading).saveAs(join(output, 'answer.txt'))
  await dialog.getByLabel('Đính kèm ảnh hoặc tài liệu').setInputFiles({ name: 'dock-note.txt', mimeType: 'text/plain', buffer: Buffer.from('The project code is DOCK-251.') })
  await dialog.getByLabel('Câu hỏi học vụ').fill('Mã dự án trong tệp là gì?')
  const uploadPromise = page.waitForResponse(r => r.url().endsWith('/assistant/stream'), { timeout: 65000 })
  await dialog.getByRole('button', { name: 'Gửi', exact: true }).click()
  const upload = await uploadPromise
  const uploadAnswer = await readAssistantStreamResult(upload, page)
  if (!upload.ok() || !uploadAnswer.answer.includes('DOCK-251')) throw new Error('Dock file submission failed')
  await dialog.getByText(uploadAnswer.answer, { exact: true }).waitFor()
  if (await dialog.getByLabel('Tệp đã chọn').count()) throw new Error('Sent attachment was not cleared')
  await page.setViewportSize({ width: 390, height: 844 })
  await dialog.waitFor({ state: 'visible' })
  await page.screenshot({ path: join(output, 'dock-mobile.png'), fullPage: true })
  const box = await dialog.boundingBox()
  if (box.width > 390 || box.x < 0 || box.y < 0) throw new Error('Mobile bounds invalid')
  await dialog.getByRole('button', { name: 'Đóng trợ lý AI' }).click()
  await page.goto('http://localhost:5175/academic/assistant')
  await page.waitForURL('**/project/overview')
  await dialog.waitFor({ state: 'visible' })
  const result = { status: response.status(), runId: answer.runId, fileRunId: uploadAnswer.runId, generationStatus: answer.generationStatus, routePreserved: true, minimizePreservesDraft: true, navigationPreservesConversation: true, panelsExclusive: true, download: true, legacyRouteOpensDock: true, errors }
  writeFileSync(join(output, 'dock-checks.json'), JSON.stringify(result, null, 2))
  console.log(JSON.stringify(result))
  if (errors.length) throw new Error('Browser errors')
} finally { await browser.close() }
